using HWAY.Payroll.Data.Context;
using HWAY.Payroll.Data.Entities;
using Microsoft.EntityFrameworkCore;

namespace HWAY.Payroll.Services.Calculations;

public sealed class CalculationSettingsService : ICalculationSettingsService
{
    private readonly AppDbContext _dbContext;

    public CalculationSettingsService(AppDbContext dbContext)
    {
        _dbContext = dbContext;
    }

    public async Task<IReadOnlyList<CalculationDto>> GetCalculationsAsync(
        CancellationToken cancellationToken = default)
    {
        await EnsureDefaultCalculationsAsync(cancellationToken);

        return await _dbContext.Calculations
            .AsNoTracking()
            .OrderBy(calculation => calculation.Id)
            .Select(calculation => new CalculationDto
            {
                Id = calculation.Id,
                Name = calculation.Name,
                Calculation = calculation.CalculationText
            })
            .ToListAsync(cancellationToken);
    }

    public async Task SaveCalculationAsync(
        CalculationDto calculation,
        CancellationToken cancellationToken = default)
    {
        await EnsureDefaultCalculationsAsync(cancellationToken);

        var name = calculation.Name.Trim();
        var calculationText = calculation.Calculation.Trim();

        if (string.IsNullOrWhiteSpace(name))
        {
            throw new InvalidOperationException("Calculation name is required.");
        }

        if (string.IsNullOrWhiteSpace(calculationText))
        {
            throw new InvalidOperationException("Calculation JSON is required.");
        }

        Calculation entity;

        if (calculation.Id > 0)
        {
            entity = await _dbContext.Calculations
                .FirstOrDefaultAsync(item => item.Id == calculation.Id, cancellationToken)
                ?? throw new InvalidOperationException($"Calculation {calculation.Id} was not found.");
        }
        else
        {
            entity = new Calculation();
            _dbContext.Calculations.Add(entity);
        }

        entity.Name = name;
        entity.CalculationText = calculationText;

        await _dbContext.SaveChangesAsync(cancellationToken);
    }

    public async Task EnsureDefaultCalculationsAsync(CancellationToken cancellationToken = default)
    {
        await _dbContext.Database.ExecuteSqlRawAsync(
            """
            create table if not exists public."Calculations" (
                "Id" integer generated by default as identity,
                "Name" character varying(100) not null,
                "Calculation" text not null,
                constraint "PK_Calculations" primary key ("Id")
            );

            create unique index if not exists "IX_Calculations_Name"
                on public."Calculations" ("Name");
            """,
            cancellationToken);

        var defaults = new[]
        {
            new Calculation
            {
                Name = DefaultPayrollCalculations.CppName,
                CalculationText = DefaultPayrollCalculations.CppCalculation
            },
            new Calculation
            {
                Name = DefaultPayrollCalculations.EiName,
                CalculationText = DefaultPayrollCalculations.EiCalculation
            },
            new Calculation
            {
                Name = DefaultPayrollCalculations.TaxName,
                CalculationText = DefaultPayrollCalculations.TaxCalculation
            }
        };

        foreach (var defaultCalculation in defaults)
        {
            var exists = await _dbContext.Calculations
                .AnyAsync(
                    calculation => calculation.Name == defaultCalculation.Name,
                    cancellationToken);

            if (exists)
            {
                continue;
            }

            _dbContext.Calculations.Add(defaultCalculation);
        }

        await _dbContext.SaveChangesAsync(cancellationToken);
    }
}
